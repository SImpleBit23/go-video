'use strict';
const assert=require('assert'),fs=require('fs'),os=require('os'),path=require('path'),url=require('url');
const root=path.resolve(__dirname,'..'),svc=path.join(root,'native/st-govideo-d');
const vk=require(path.join(svc,'vk')),oauth=require(path.join(svc,'oauth'));
const {Daemon}=require(path.join(svc,'ytd'));
let checks=0;
function ok(v,m){assert.ok(v,m);checks++;}
async function main(){
    ['https://vkvideo.ru/video-123_456','https://vk.com/video-123_456','https://vk.ru/video-123_456','https://vk.com/video_ext.php?oid=-123&id=456','-123_456'].forEach(x=>{assert.strictEqual(vk.parseLink(x),'-123_456');checks++;});
    ['https://evil.test/video-123_456','https://vk.com@evil.test/video-123_456','https://vk.com:8080/video-123_456','https://vkvideo.ru/video../passwd','https://vkvideo.ru/video-123_456/../../etc/passwd','https://127.0.0.1/video-123_456'].forEach(x=>{assert.strictEqual(vk.parseLink(x),null);checks++;});
    assert.strictEqual(vk.parseLink('BMW G26'),undefined);checks++;
    const config={client_id:'12345',redirect_uri:'https://example.test/vk/callback',scope:'video'};
    assert.throws(()=>oauth.begin({client_id:'12345'}));checks++;
    const request=oauth.begin(config),q=url.parse(request.url,true).query;
    ok(q.code_challenge.length===43 && q.state && q.response_type==='code','real PKCE authorization URL');
    ok(!request.url.includes(request.pending.verifier),'verifier never leaves in the QR');
    const callback=config.redirect_uri+'?state='+request.pending.state+'&code=fixture&device_id=device';
    const exchange=oauth.finish(request.pending,callback);
    assert.strictEqual(exchange.fields.code_verifier,request.pending.verifier);checks++;
    assert.throws(()=>oauth.finish(request.pending,callback.replace(request.pending.state,'wrong')));checks++;
    assert.throws(()=>oauth.finish(request.pending,callback.replace('example.test','attacker.test')));checks++;
    assert.throws(()=>oauth.finish(request.pending,callback,request.pending.created+610000));checks++;
    const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'govideo-test-')),events=[],requests=[];
    const d=new Daemon({stateDir:path.join(tmp,'state'),cacheDir:path.join(tmp,'cache'),logDir:path.join(tmp,'log'),log:()=>{},noSetuid:true});
    d.emit=m=>events.push(m);d.positions=()=>({'-123_456':{title:'История',ms:12000,at:10,duration_s:90}});
    let denied=false;
    d.fetch=async req=>{
        const u=url.parse(req.url,true);requests.push({method:u.pathname.split('/').pop(),q:u.query});
        let response;
        const method=requests[requests.length-1].method;
        if(method==='users.get')response=[{id:42}];
        else if(denied && method==='video.get')return {status:200,body:JSON.stringify({error:{error_code:15}})};
        else if(method==='video.getAlbums')response={count:1,items:[{owner_id:42,id:3,title:'Тест',count:1}]};
        else if(method==='groups.get')response={count:1,items:[{id:123,name:'BMW',screen_name:'bmw'}]};
        else response={count:1,items:[{owner_id:-123,id:456,title:'Видео',duration:90,image:[{width:320,url:'https://sun9.userapi.com/a.jpg'}]}],groups:[{id:123,name:'BMW'}]};
        return {status:200,body:JSON.stringify({response})};
    };
    await d.onLine(JSON.stringify({cmd:'search',q:'https://vkvideo.ru/video-123_456'}));
    ok(events.pop().items[0].id==='-123_456' && !requests.length,'public link resolved without credentials');
    await d.onLine(JSON.stringify({cmd:'feed',which:'hist'}));ok(events.pop().items.length===1,'local history works signed out');
    await d.onLine(JSON.stringify({cmd:'favorite',id:'-123_456'}));ok(events.pop().items.length===1,'favorite added through real dispatch');
    await d.onLine(JSON.stringify({cmd:'favorite',id:'-123_456'}));ok(events.pop().items.length===0,'favorite toggled off');
    await d.account.importToken('fixture-not-a-real-token-123456');
    ok(d.account.status().state==='signed_in' && fs.existsSync(d.account.file),'VK token verifies video permission before persistence');
    d.account.web=async()=>{if(denied)throw Object.assign(new Error('denied'),{userMessage:'Ошибка доступа'});return {items:[{owner_id:-123,id:456,title:'Видео',image:[]}],groups:[{id:123,name:'BMW'}]};};
    await d.onLine(JSON.stringify({cmd:'search',q:'BMW'}));ok(events.pop().items[0].channel==='BMW','VK search names mapped to GUI');
    await d.onLine(JSON.stringify({cmd:'feed',which:'home'}));ok(events.pop().items[0].title==='Видео','own video feed');
    await d.onLine(JSON.stringify({cmd:'channels'}));ok(events.pop().items[0].id==='-123','communities mapped');
    await d.onLine(JSON.stringify({cmd:'channel',id:'-123'}));ok(events.pop().items.length===1,'community videos');
    await d.onLine(JSON.stringify({cmd:'playlists'}));ok(events.pop().items[0].id==='42_3','VK albums');
    await d.onLine(JSON.stringify({cmd:'playlist',id:'42_3'}));ok(events.pop().items.length===1,'album video list');
    denied=true;const before=fs.readFileSync(d.account.file,'utf8');
    await assert.rejects(d.account.importToken('fixture-denied-token-123456'));checks++;
    assert.strictEqual(fs.readFileSync(d.account.file,'utf8'),before);checks++;
    const cachedFeed = d.account.feed('home');
    ok(events.at(-1).partial && events.at(-1).items[0].id === '-123_456', 'cached catalog appears before the refresh');
    await cachedFeed;
    ok(!events.at(-1).partial && !events.at(-1).error && events.at(-1).items.length === 1, 'refresh failure keeps the cache visible');
    fs.unlinkSync(d.account.homeFile);
    await d.account.feed('home');ok(events.pop().error.includes('доступ'),'cold catalog reports the access error');
    denied=false;
    await d.account.start();ok(events.pop().state==='error','guest build does not advertise an unimplemented login');
    fs.writeFileSync(path.join(d.opts.stateDir, 'oauth-config.json'), JSON.stringify(config));
    await d.onLine(JSON.stringify({cmd:'auth'}));
    const login = events.pop();
    ok(login.state === 'code' && login.flow === 'manual' && login.url.startsWith('https://id.vk.com/authorize?'), 'configured QR starts PKCE');
    const loginState = new URL(login.url).searchParams.get('state');
    const loginReturn = config.redirect_uri+'?state='+loginState+'&code=fixture&device_id=device';
    d.account.oauth = async (fields) => {
        ok(fields.code === 'fixture' && fields.state === loginState && fields.device_id === 'device', 'PKCE exchange receives the validated callback');
        return {state: fields.state, access_token:'fixture-login-token-123456', refresh_token:'fixture-refresh', expires_in:3600};
    };
    await d.account.finish(loginReturn);
    ok(JSON.parse(fs.readFileSync(d.account.file)).refresh_token === 'fixture-refresh', 'verified video account is saved with its refresh token');
    await assert.rejects(d.account.finish(loginReturn));checks++;
    d.account.signOut();ok(!fs.existsSync(d.account.file) && d.account.status().state==='signed_out','sign out clears saved credential');
    const {Model}=require(path.join(root,'apps/st_go_video/yt'));
    const sent=[],model=new Model(x=>{sent.push(x);return true;},()=>{});
    model.setConnected(true);model.onMsg({ev:'hello',caps:['vk','hist','download'],service:'0.1.0'});
    model.onMsg({ev:'auth',state:'signed_out'});ok(model.feed('wl'),'GUI permits local favorites as guest');
    model.onMsg({ev:'feed',which:'wl',items:[{id:'-123_456',title:'Тест',duration_s:90}]});
    ok(model.feeds.wl.items.length===1,'GUI accepts real VK ids');
    model.onMsg({ev:'results',q:'BMW',items:[{id:'-123_456',title:'Тест',duration_s:90}]});
    ok(model.results.length===1,'search results accept VK ids');
    const qr=require(path.join(root,'apps/st_go_video/qr'));
    ok(qr.encode(request.url).length>33,'full OAuth URL fits a real QR, no redirect fallback');
    assert(path.resolve(tmp).startsWith(path.resolve(os.tmpdir())+path.sep+'govideo-test-'));
    fs.rmSync(tmp,{recursive:true,force:true});
    console.log(JSON.stringify({checks,vehicleAccessed:false,realVkAccountAccessed:false,oauthConfigurationRequired:false}));
}
main().catch(e=>{console.error(e.stack);process.exit(1);});
